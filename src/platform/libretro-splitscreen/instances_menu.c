/* GBA keymask bits, matching libretro.c's keymap order (libretro pad id i ->
 * bit i). Local copies so this file needs no libretro.h. */
#define K_A (1u << 0)
#define K_START (1u << 3)
#define K_RIGHT (1u << 4)
#define K_LEFT (1u << 5)
#define K_L (1u << 9)
#define K_R (1u << 8)

static bool sActive;
static bool sConfirmed;
static int sSel; /* 0..2 -> 2..4 players */
static uint32_t sLastKeys;
static unsigned sFrames;


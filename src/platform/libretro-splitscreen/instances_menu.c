/* In-core boot menu: "How many players?" rendered through the normal video
 * callback before any sessions spin up. RetroArch just sees a core that is
 * still loading; nothing about the libretro contract changes.
 *
 * Why: the frontend's core option (Players per ROM) is a persisted default,
 * and the Load Content subsystem picker does not re-fire when a game is
 * relaunched from a playlist/Recents. Rendering our own menu inside the core
 * puts the per-boot choice on the TV, driven by Player 1's pad.
 *
 * UX decision (2026-10-01): press-to-start only — the menu waits forever
 * until P1 presses A/Start; nothing auto-boots.
 */
#include "instances_menu.h"


static const uint8_t* glyphFor(char c) {
	if (c < 0x20 || c >= 0x7F) {
		return NULL;
	}
	return tomThumb[c - 0x20];
}

static void px(struct sp_video* vid, int x, int y, uint16_t color) {
	if (x >= 0 && x < (int) vid->width && y >= 0 && y < (int) vid->height) {
		vid->out[y * vid->width + x] = color;
	}
}

static void fillRect(struct sp_video* vid, int ox, int oy, int w, int h, uint16_t color) {
	for (int y = oy; y < oy + h; ++y) {
		for (int x = ox; x < ox + w; ++x) {
			px(vid, x, y, color);
		}
	}
}

static void rect(struct sp_video* vid, int ox, int oy, int w, int h, uint16_t color) {
	for (int x = ox; x < ox + w; ++x) {
		px(vid, x, oy, color);
		px(vid, x, oy + h - 1, color);
	}
	for (int y = oy; y < oy + h; ++y) {
		px(vid, ox, y, color);
		px(vid, ox + w - 1, y, color);
	}
}

static void drawText(struct sp_video* vid, int ox, int oy, int scale, uint16_t color, const char* text) {
	int cx = ox;
	for (const char* c = text; *c; ++c) {
		const uint8_t* g = glyphFor(*c);
		if (g) {
			for (int row = 0; row < 5; ++row) {
				for (int col = 0; col < 3; ++col) {
					if (g[row] & (0x4 >> col)) {
						fillRect(vid, cx + col * scale, oy + row * scale, scale, scale, color);
					}
				}
			}
		}
		cx += 4 * scale;
	}
}

static int textWidth(int scale, const char* text) {
	return (int) strlen(text) * 4 * scale - scale;
}

#define MENU_W 480
#define MENU_H 160
#define CELL_W 100
#define CELL_H 64
#define CELL_Y 56

void spMenuFrame(struct sp_video* vid, void (*poll)(void), uint32_t (*readKeys)(unsigned port)) {
	++sFrames;
	if (poll) {
		poll();
	}
	uint32_t keys = readKeys ? readKeys(0) : 0;
	uint32_t pressed = keys & ~sLastKeys;
	sLastKeys = keys;
	if (pressed & (K_LEFT | K_L)) {
		if (sSel > 0) {
			--sSel;
		}
	}
	if (pressed & (K_RIGHT | K_R)) {
		if (sSel < 2) {
			++sSel;
		}
	}
	if (pressed & (K_A | K_START)) {
		sConfirmed = true;
	}

	/* Background. */
	fillRect(vid, 0, 0, vid->width, vid->height, 0x0000);

	/* Title. */
	const char* title = "HOW MANY PLAYERS?";
	drawText(vid, (MENU_W - textWidth(2, title)) / 2, 14, 2, 0xFFFF, title);

	/* Choices: 2 / 3 / 4 players, each in that seat's color. */
	for (int i = 0; i < 3; ++i) {
		int x = 70 + i * 120;
		uint16_t color = spPlayerColors[i];
		char big[2] = { (char) ('2' + i), 0 };
		int gx = x + (CELL_W - 3 * 6) / 2;
		if (i == sSel) {
			rect(vid, x - 3, CELL_Y - 3, CELL_W + 6, CELL_H + 6, 0xFFFF);
		}
		rect(vid, x, CELL_Y, CELL_W, CELL_H, color);
		drawText(vid, gx, CELL_Y + 8, 6, 0xFFFF, big);
		const char* cap = "PLAYERS";
		drawText(vid, x + (CELL_W - textWidth(1, cap)) / 2, CELL_Y + CELL_H - 14, 1, color, cap);
	}

	/* Footer hint, blinking so it reads as "waiting for input". */
	if (sFrames % 60u < 40u) {
		const char* hint = "LEFT RIGHT TO CHOOSE - A OR START TO BOOT";
		drawText(vid, (MENU_W - textWidth(1, hint)) / 2, 140, 1, 0x8410, hint);
	}
}

void spMenuStart(int defaultPlayers) {
	sActive = true;
	sConfirmed = false;
	sSel = defaultPlayers < 2 ? 0 : (defaultPlayers > 4 ? 2 : defaultPlayers - 2);
	sLastKeys = 0;
	sFrames = 0;
}

bool spMenuActive(void) {
	return sActive;
}

bool spMenuTakeConfirmed(void) {
	if (!sConfirmed) {
		return false;
	}
	sConfirmed = false;
	sActive = false;
	return true;
}

int spMenuSelection(void) {
	return sSel + 2;
}

@ DualBoy linktest ROM boot header + entry point.
@
@ Layout: 0x000 branch to _start, 0x004 Nintendo logo (156 bytes),
@ 0x0A0 title/code fields, 0x0C0 _start.
@
@ The branch at 0x000 is `b _start` with _start at 0xC0, so the branch
@ encodes as 2E 00 00 EA — the same 4 bytes every commercial GBA cart has.
@ mGBA's BIOS-logo check CRCs bytes 4..0x9F; the logo below is the canonical
@ 156-byte Nintendo logo, verified to hash to mGBA's LOGO_CRC32 (0xD0BEB55E),
@ so the ROM boots through the real BIOS path with no "Invalid logo" warning.

    .arm
    .section .text
    .global _start

    @ 0x000: branch to the entry point at 0xC0
    b   _start

    @ 0x004: Nintendo logo, 156 bytes (extracted from a legal test cart and
    @ verified to CRC to mGBA's LOGO_CRC32 0xD0BEB55E)
    .byte 0x24,0xFF,0xAE,0x51,0x69,0x9A,0xA2,0x21
    .byte 0x3D,0x84,0x82,0x0A,0x84,0xE4,0x09,0xAD
    .byte 0x11,0x24,0x8B,0x98,0xC0,0x81,0x7F,0x21
    .byte 0xA3,0x52,0xBE,0x19,0x93,0x09,0xCE,0x20
    .byte 0x10,0x46,0x4A,0x4A,0xF8,0x27,0x31,0xEC
    .byte 0x58,0xC7,0xE8,0x33,0x82,0xE3,0xCE,0xBF
    .byte 0x85,0xF4,0xDF,0x94,0xCE,0x4B,0x09,0xC1
    .byte 0x94,0x56,0x8A,0xC0,0x13,0x72,0xA7,0xFC
    .byte 0x9F,0x84,0x4D,0x73,0xA3,0xCA,0x9A,0x61
    .byte 0x58,0x97,0xA3,0x27,0xFC,0x03,0x98,0x76
    .byte 0x23,0x1D,0xC7,0x61,0x03,0x04,0xAE,0x56
    .byte 0xBF,0x38,0x84,0x00,0x40,0xA7,0x0E,0xFD
    .byte 0xFF,0x52,0xFE,0x03,0x6F,0x95,0x30,0xF1
    .byte 0x97,0xFB,0xC0,0x85,0x60,0xD6,0x80,0x25
    .byte 0xA9,0x63,0xBE,0x03,0x01,0x4E,0x38,0xE2
    .byte 0xF9,0xA2,0x34,0xFF,0xBB,0x3E,0x03,0x44
    .byte 0x78,0x00,0x90,0xCB,0x88,0x11,0x3A,0x94
    .byte 0x65,0xC0,0x7C,0x63,0x87,0xF0,0x3C,0xAF
    .byte 0xD6,0x25,0xE4,0x8B,0x38,0x0A,0xAC,0x72
    .byte 0x21,0xD4,0xF8,0x07

    @ 0x0A0: game title (12 bytes)
    .ascii "DUALBOY LINK"
    @ 0x0AC: game code (4 bytes)
    .ascii "DLNK"
    @ 0x0B0: maker code (2 bytes)
    .ascii "DB"
    @ 0x0B2: fixed value, unit code, device type
    .byte 0x96, 0x00, 0x00
    @ 0x0B5-0x0BB: reserved (7 bytes)
    .byte 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    @ 0x0BC: version, 0x0BD: header checksum (patched by fix_header.py)
    .byte 0x00, 0x00
    @ 0x0BE-0x0BF: reserved
    .byte 0x00, 0x00

    @ 0x0C0: entry point (aligned — header is exactly 0xC0 bytes)
_start:
    ldr sp, =0x03007F00     @ main stack at top of IWRAM
    @ zero .bss (EWRAM)
    ldr r0, =__bss_start
    ldr r1, =__bss_end
    mov r2, #0
1:
    cmp r0, r1
    bcs 2f
    str r2, [r0], #4
    b 1b
2:
    bl  main
3:
    b 3b                     @ main must never return
